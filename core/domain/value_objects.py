"""Domain Value Objects for BankRange.

Value Objects are immutable, identity-less objects that describe
characteristics of domain entities. They are compared by structural
equality, not by identity.

In BankRange's ubiquitous language:
- An IP address belongs to a network segment and a workstation.
- A MAC address uniquely identifies a network interface.
- An OS type classifies the operating system running on a workstation.
- An event type categorizes what happened (authentication, network, etc.).
- A severity level indicates the urgency of the event (syslog standard).
"""

from enum import StrEnum
from ipaddress import IPv4Address
from typing import Annotated

from pydantic import BaseModel, Field


class OSType(StrEnum):
    """Operating system types found in a typical bank environment.

    Banks typically standardize on Windows for teller/backoffice stations,
    with Linux for servers and a small pool of macOS for executives.
    """

    WINDOWS = "windows"
    LINUX = "linux"
    MACOS = "macos"


class IPAddress(BaseModel):
    """An IPv4 address within the bank's private network.

    Validates that the address belongs to RFC 1918 private ranges
    (10.x.x.x, 172.16-31.x.x, 192.168.x.x), as bank workstations
    should never have public IPs.
    """

    model_config = {"frozen": True}

    value: Annotated[str, Field(description="IPv4 address string")]

    def model_post_init(self, __context: object) -> None:
        """Validate that the IP is a valid private IPv4 address."""
        try:
            addr = IPv4Address(self.value)
        except ValueError as e:
            raise ValueError(f"Invalid IPv4 address: {self.value}") from e

        if not addr.is_private:
            raise ValueError(
                f"Bank workstations must use private IPs (RFC 1918), "
                f"got public address: {self.value}"
            )


class MacAddress(BaseModel):
    """A MAC address for a network interface.

    Validates format as six groups of two hex digits separated by colons
    (e.g., 'AA:BB:CC:DD:EE:FF'). Stored in uppercase.
    """

    model_config = {"frozen": True}

    value: Annotated[
        str,
        Field(
            pattern=r"^([0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}$",
            description="MAC address in colon-separated hex format",
        ),
    ]

    def model_post_init(self, __context: object) -> None:
        """Normalize MAC address to uppercase."""
        # frozen=True prevents direct assignment, so we use __dict__
        object.__setattr__(self, "value", self.value.upper())


class EventType(StrEnum):
    """Categories of events generated by bank workstations.

    Each type maps to a family of specific event_ids that a workstation
    can emit. For example, AUTHENTICATION covers login, logout,
    failed_login, password_change, and session_timeout events.
    """

    AUTHENTICATION = "authentication"
    NETWORK = "network"
    PROCESS = "process"
    FILE_ACCESS = "file_access"
    EMAIL = "email"
    APPLICATION = "application"
    SYSTEM = "system"


class Severity(StrEnum):
    """Syslog-standard severity levels for log events.

    Simplified to 4 levels for the simulation. In a real SIEM,
    you'd use all 8 syslog levels, but for training purposes
    these 4 cover the detection spectrum:
    - INFO: Normal operations (baseline noise).
    - WARNING: Anomalies worth investigating.
    - ERROR: Failures that may indicate attacks.
    - CRITICAL: Active threats or system compromise.
    """

    INFO = "info"
    WARNING = "warning"
    ERROR = "error"
    CRITICAL = "critical"

