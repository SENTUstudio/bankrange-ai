"""LogEvent entity — the core output of the BankRange simulator.

Every workstation in the simulated bank topology produces LogEvents.
Each event flows through the pipeline: Workstation → Kafka → Loki → Grafana.

The LogEvent schema aligns with the PRD acceptance criteria (Section 5):
  - timestamp, hostname, ip_address, event_id, user, os_type
  - Plus enrichment fields: event_type, severity, message, metadata

This entity is part of the CORE domain — it has ZERO infrastructure
dependencies. Serialization to JSON happens at the adapter boundary.
"""

import uuid
from datetime import datetime, timezone
from typing import Annotated, Any

from pydantic import BaseModel, Field

from core.domain.value_objects import EventType, OSType, Severity


class LogEvent(BaseModel):
    """A single log event generated by a bank workstation.

    This is the atomic unit of data flowing through the entire pipeline.
    It carries enough context for a SIEM analyst to understand:
    - WHAT happened (event_type, event_id, message)
    - WHERE it happened (hostname, ip_address, branch_code)
    - WHO triggered it (username)
    - WHEN it happened (timestamp)
    - HOW serious it is (severity)

    Business rules:
    - event_id is unique per event (UUID v4).
    - timestamp must be timezone-aware (UTC).
    - hostname and ip_address come from the source Workstation.
    - username comes from the assigned Employee (or 'SYSTEM' for
      automated events).
    """

    model_config = {"frozen": True}

    event_id: Annotated[
        uuid.UUID,
        Field(
            default_factory=uuid.uuid4,
            description="Unique event identifier",
        ),
    ]
    timestamp: Annotated[
        datetime,
        Field(
            default_factory=lambda: datetime.now(timezone.utc),
            description="UTC timestamp of event generation",
        ),
    ]
    hostname: Annotated[
        str,
        Field(
            min_length=1,
            max_length=64,
            description="Source workstation hostname",
        ),
    ]
    ip_address: Annotated[
        str,
        Field(
            min_length=7,
            max_length=15,
            description="Source workstation IP address",
        ),
    ]
    os_type: Annotated[
        OSType,
        Field(description="Operating system of the source workstation"),
    ]
    username: Annotated[
        str,
        Field(
            min_length=1,
            max_length=64,
            description="User who triggered the event (or 'SYSTEM')",
        ),
    ]
    branch_code: Annotated[
        str,
        Field(
            pattern=r"^[A-Z]{3}\d{3,4}$",
            description="Branch code where the event originated",
        ),
    ]
    event_type: Annotated[
        EventType,
        Field(description="Category of the event"),
    ]
    severity: Annotated[
        Severity,
        Field(
            default=Severity.INFO,
            description="Severity level of the event",
        ),
    ]
    message: Annotated[
        str,
        Field(
            min_length=1,
            max_length=512,
            description="Human-readable event description",
        ),
    ]
    metadata: Annotated[
        dict[str, Any],
        Field(
            default_factory=dict,
            description="Additional event-specific data (flexible schema)",
        ),
    ]

    def to_raw_format(self) -> str:
        """Serialize to a chaotic string based on Operating System.

        This intentional break from JSON purity forces Data Engineers 
        to build grok/regex ETL pipelines for normalization.
        """
        ts_syslog = self.timestamp.strftime("%b %d %H:%M:%S")
        ts_iso = self.timestamp.isoformat()
        
        if self.os_type == OSType.LINUX:
            # Legacy Syslog RFC 3164 format
            return f"<{134}>{ts_syslog} {self.hostname} {self.event_type.value}[{self.event_id.hex[:8]}]: {self.username} - {self.severity.value.upper()} - {self.message} (src={self.ip_address} branch={self.branch_code})"
            
        elif self.os_type == OSType.WINDOWS:
            # Flattened XML mimicking Windows Event Log
            return (
                f'<Event><System><Provider Name="{self.event_type.value}"/><TimeCreated SystemTime="{ts_iso}"/>'
                f'<Computer>{self.hostname}</Computer><Security UserID="{self.username}"/></System>'
                f'<EventData><Data Name="Message">{self.message}</Data><Data Name="Level">{self.severity.value}</Data>'
                f'<Data Name="IP">{self.ip_address}</Data><Data Name="Branch">{self.branch_code}</Data></EventData></Event>'
            )
            
        elif self.os_type == OSType.MACOS:
            # Tab-separated strings simulating rigid CSV/ASL dumps
            return f"{ts_iso}\t{self.hostname}\t{self.username}\t{self.os_type.value}\t{self.event_type.value}\t{self.severity.value}\t{self.message}\t{self.ip_address}\t{self.branch_code}"
            
        # Fallback to stringified dict if unknown
        return str(self.model_dump())
